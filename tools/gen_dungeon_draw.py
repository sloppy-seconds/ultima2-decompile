#!/usr/bin/env python3
"""Generate engine/src/game/dungeon_draw.inc from the byte-proven asm tree.

The dungeon renderer in the original is twelve short routines that each issue one
to nine calls to the line drawer (asm/67B3) after loading its four coordinate
registers from a block of eight-entry depth tables that live in CS. The registers
are NOT reset between calls, so a faithful transcription has to carry them across
exactly as the CPU does. This script does that mechanically instead of by hand.

Read-only against asm/. Writes the generated C to stdout.
"""
import re, pathlib

ASM = pathlib.Path("/var/home/paul/Projects/decompile-u2-v2/asm")
EXE = pathlib.Path("/var/home/paul/Projects/decompile-u2-v2/original/ultimaii.exe")

# runtime cs offset -> C table name. Derived from the depth tables at cs:620d..
RAW = {}
data = EXE.read_bytes()
def rt(a):            # runtime cs offset -> file bytes
    return data[a + 0x200]

# Every cs:NNNN(%di) operand actually referenced, plus the eight base tables.
refs = set()
for p in ASM.glob("*.asm"):
    for m in re.finditer(r"mov\s+%cs:0x([0-9a-fA-F]{4})\(%di\),%al", p.read_text()):
        off = int(m.group(1), 16)
        if 0x6200 <= off <= 0x6290:      # the dungeon depth-table block only
            refs.add(off)
for base in (0x620D, 0x620E, 0x6217, 0x6218, 0x6221, 0x6222, 0x6229, 0x622A):
    refs.add(base)

def tname(off):
    return "T_%04X" % off

# group into 8-entry tables starting at each referenced offset
TABLES = sorted(refs)

# The eight base depth tables get readable aliases.
ALIAS = {
    0x620D: "DG_XL", 0x620E: "DG_XL1", 0x6217: "DG_XR", 0x6218: "DG_XR1",
    0x6221: "DG_YT", 0x6222: "DG_YT1", 0x6229: "DG_YB", 0x622A: "DG_YB1",
}

print("/* GENERATED by tools/gen_dungeon_draw.py — do not edit by hand. */")
print("/* Each table is eight bytes read verbatim from the CS depth-table block.")
print(" * Source: original/ultimaii.exe, cs offsets named in each comment.      */")
for off in TABLES:
    vals = ", ".join("0x%02x" % rt(off + i) for i in range(8))
    nm = ALIAS.get(off, tname(off))
    print("static const uint8_t %s[8] = { %s };   /* cs:%04X */" % (nm, vals, off))
print()

# ---- shape routines -------------------------------------------------------
# runtime file -> (asm file, entry label)
ROUTINES = [
    ("6291_sub_6291", "L_006491"), ("6304_sub_6304", "L_006504"),
    ("6377_sub_6377", "L_006577"), ("63CE_sub_63ce", "L_0065CE"),
    ("6425_sub_6425", "L_006625"), ("648D_sub_648d", "L_00668D"),
    ("64E2_sub_64e2", "L_0066E2"), ("653F_sub_653f", "L_00673F"),
    ("6594_sub_6594", "L_006794"), ("660C_sub_660c", "L_00680C"),
    ("6684_sub_6684", "L_006884"), ("66CB_sub_66cb", "L_0068CB"),
]

SLOT = {"0x479": "x1", "0x47a": "y1", "0x47b": "x2", "0x47c": "y2"}

def parse(fname):
    """Return the op list for one routine, in execution order."""
    txt = (ASM / (fname + ".asm")).read_text()
    ops = []
    for ln in txt.splitlines():
        if ln.startswith("#") or not ln.strip():
            continue
        s = ln.strip()
        m = re.match(r"mov\s+%cs:0x([0-9a-fA-F]{4})\(%di\),%al", s)
        if m:
            off = int(m.group(1), 16)
            ops.append(("src", ALIAS.get(off, tname(off))))
            continue
        m = re.match(r"mov\s+\$0x([0-9a-fA-F]{1,2}),%al", s)
        if m:
            ops.append(("imm", "0x" + m.group(1)))
            continue
        m = re.match(r"mov\s+%al,(0x47[9abc])", s)
        if m:
            ops.append(("set", SLOT[m.group(1)]))
            continue
        m = re.match(r"mov\s+(0x47[9abc]),%al", s)
        if m:
            ops.append(("get", SLOT[m.group(1)]))
            continue
        if s.startswith("call L_0069b3"):
            ops.append(("line", None))
            continue
        m = re.match(r"call (L_00[0-9a-fA-F]{4})", s)
        if m:
            ops.append(("call", m.group(1)))
    return ops

# label -> routine name, so `call` ops become C calls
LBL2FN = {}
for fname, entry in ROUTINES:
    LBL2FN[entry.upper()] = "dg_" + fname.split("_")[0].lower()

for fname, entry in ROUTINES:
    ops = parse(fname)
    fn = "dg_" + fname.split("_")[0].lower()
    print("/* %s  (asm/%s.asm, entry %s) */" % (fn, fname, entry))
    print("static void %s(dg_view *v)" % fn)
    print("{")
    pending = None
    for kind, arg in ops:
        if kind == "src":
            pending = arg
        elif kind == "imm":
            pending = arg
        elif kind == "set":
            # `mov %al,0x479` then `mov %al,0x47b` stores ONE load into two
            # registers, so the load stays live in al until the next load.
            if pending and pending.startswith("0x"):
                print("    v->%s = %s;" % (arg, pending))
            else:
                print("    v->%s = %s[v->d];" % (arg, pending if pending else "0"))
        elif kind == "get":
            pending = "v->" + arg
        elif kind == "line":
            print("    dg_line(v);")
            pending = None
        elif kind == "call":
            tgt = LBL2FN.get(arg.upper())
            print("    %s(v);" % tgt if tgt else "    /* call %s (outside this set) */" % arg)
    print("}")
    print()
