#!/usr/bin/env python3
"""
fmtowns_theme.py — derive the format-v2 FM Towns theme from the player's own disc.

This is the FM Towns half of the deleted tools/build_themes.py, restored as a
developer tool rather than resurrected whole. The split is deliberate and it is the
ruling from docs/install-design.md § 10: the **v1 reshape** has exactly one builder,
in the shipped binary (engine/src/core/themes.c), because two builders of one format
are two definitions of it. What stays here is the part a shipped binary has no
business doing — reading a CD image, decoding GRAPH banks, and experimenting with
which FM frames a DOS art index should map to.

So the two tools have different jobs, not overlapping ones:

  * `u2 --install --fmtowns-media-dir DIR`  builds the theme for a player, from
    the crosswalk compiled into the binary as engine/content/fmtowns_map.h.
  * this tool  builds the same theme from disasm/fmtowns-crosswalk.tsv on a dev
    box, and is what you use to look at more FM Towns media and extend the theme.

It imports the ISO reader and the bank decoder from tools/fmtowns_xwalk.py rather
than carrying its own, for the reason that file states: no second ISO parser and no
second decoder, both of which would be free to drift.

One deliberate difference from the code it was restored from: the MAP.TSV header no
longer names its writer. The old line said "generated by tools/build_themes.py",
which is now false, and a provenance comment that names a tool that no longer exists
is worse than none. Dropping the writer name entirely is what makes the C port
checkable: both implementations now produce byte-identical output, so the gate is a
straight comparison of all four files rather than a comparison with one line excused.

USAGE
    python3 tools/fmtowns_theme.py --out themes/fmtowns
    python3 tools/fmtowns_theme.py --out /var/tmp/probe --xwalk disasm/fmtowns-crosswalk.tsv

The disc is found at references/fmtowns/*.img (first, sorted), the same rule
tools/fmtowns_xwalk.py uses. A missing disc or crosswalk is a hard stop, never an
empty theme: a themes tree that quietly omits the FM Towns art renders as a theme
bug and not a build bug.
"""

import os
import sys
import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FMTOWNS_XWALK = "disasm/fmtowns-crosswalk.tsv"
FMTOWNS_NAME = "fmtowns"
FMTOWNS_SCOPE = "overworld,towns"      # the crosswalk's own scope caveat, verbatim

sys.path.insert(0, str(REPO / "tools"))


def load_crosswalk(path):
    """[(art_index, [BANK/tile, ...]), ...] in file order. Rows are tab-separated
    and the header is comments, same contract `--check` gates."""
    rows = []
    with open(path, encoding="utf-8") as fh:
        for ln in fh:
            ln = ln.rstrip("\n")
            if not ln or ln.startswith("#"):
                continue
            cols = ln.split("\t")
            if len(cols) < 2:
                continue
            toks = [t.strip() for t in cols[1].split(",") if t.strip()]
            rows.append((int(cols[0], 16), toks))
    return rows


def fmtowns_theme(xwalk_path=None):
    """Derive the v2 theme as {relpath: bytes}. Returns (files, (stats, problems)).

    A missing disc or crosswalk is a hard stop, not an empty theme: a themes tree
    that quietly omits the FM Towns art renders as a theme bug and not a build
    bug, which is the exact failure this whole tool is built against.
    """
    problems = []
    xwalk = Path(xwalk_path) if xwalk_path else REPO / FMTOWNS_XWALK
    if not xwalk.is_file():
        raise SystemExit(f"no crosswalk at {xwalk} — regenerate it with "
                         f"`python3 tools/fmtowns_xwalk.py --export` before "
                         f"building a fmtowns theme")
    try:
        import fmtowns_xwalk as fx
    except ImportError as e:
        raise SystemExit(f"cannot import tools/fmtowns_xwalk.py to read the FM "
                         f"banks ({e}) — the v2 theme needs its ISO reader")
    if not os.path.isdir(fx.DISC):
        raise SystemExit(f"no FM Towns media in {fx.DISC}")
    files = fx.disc_files(fx.find_disc())

    banks = {}
    def tile_pixels(token):
        bank, _, n = token.partition("/")
        bank = bank.upper()
        if bank not in banks:
            key = bank + ".TIF"
            if key not in files:
                raise SystemExit(f"no GRAPH/{key} on the FM Towns disc")
            banks[bank] = fx.decode_bank(files[key])
        tiles = banks[bank]
        i = int(n)
        if i < 0 or i >= len(tiles):
            raise SystemExit(f"{token}: bank {bank} has {len(tiles)} tiles")
        return tiles[i]

    def pack(px):
        """index list -> 4bpp packed rows, high nibble = left pixel. The banks
        measure zero nibbles above 7, so the upper half of the field is simply
        never set; nothing here remaps or clamps."""
        out = bytearray(len(px) // 2)
        for i in range(0, len(px), 2):
            out[i // 2] = ((px[i] & 0xF) << 4) | (px[i + 1] & 0xF)
        return bytes(out)

    pool, order = {}, []
    rows = load_crosswalk(xwalk)
    map_lines = []
    multi = 0
    for art, toks in rows:
        idxs = []
        for t in toks:
            if t not in pool:
                pool[t] = len(order)
                order.append(t)
            idxs.append(pool[t])
        if len(idxs) > 1:
            multi += 1
        map_lines.append((art, idxs, toks))
    if len(rows) != 64:
        problems.append(f"crosswalk has {len(rows)} rows, expected 64")
    missing = sorted(set(range(64)) - {a for a, _, _ in map_lines})
    if missing:
        problems.append(f"crosswalk has no row for art "
                        f"{', '.join(f'{m:02X}' for m in missing)}")

    tiles = b"".join(pack(tile_pixels(t)) for t in order)

    # PALETTE.RGB: 16 x 3. Only 0..7 are measured (§ 3 of fmtowns-graphics.md);
    # 8..15 are zero-filled because the art never indexes above 7, and that is
    # stated here rather than left for someone to discover as a colour bug.
    pal = bytearray(48)
    for i, (r, g, b) in enumerate(fx.PAL[:8]):
        pal[i * 3:i * 3 + 3] = bytes((r, g, b))

    ini = (
        "[theme]\n"
        f"name = {FMTOWNS_NAME}\n"
        f"tile_w = {fx.TILE_W}\n"
        f"tile_h = {fx.TILE_H}\n"
        "bpp = 4\n"
        "pixel = nibble-high-left\n"
        "transparent_index = 0\n"
        "palette = PALETTE.RGB\n"
        "map = MAP.TSV\n"
        "identity = no\n"
        f"scope = {FMTOWNS_SCOPE}\n"
        "source = FM Towns (1990) GRAPH banks\n"
        "frames = first\n"
        f"tiles_pool = {len(order)}\n"
        f"art_count = {len(map_lines)}\n"
        f"art_with_multiple_frames = {multi}\n"
        f"crosswalk = {FMTOWNS_XWALK}\n"
        "# `frames = first` is a slice-B policy, not a claim about the original:\n"
        "# MAP.TSV keeps every frame the crosswalk names, and the engine draws\n"
        "# list[0] until animation exists. The frames are in TILES, so nothing\n"
        "# was thrown away to get here.\n"
        "# `transparent_index = 0` is measured, not assumed: 14 of 14 ENEMY2 tiles\n"
        "# and 6 of 7 EXTRA tiles use index 0, covering 43 and 35 percent of their\n"
        "# pixels, while only 2 of 43 MAP2_1 terrain tiles use it at all and one of\n"
        "# those is a single pixel. Terrain keeps its real black at index 3, which\n"
        "# the palette also carries -- two blacks, one of them spare. That is what\n"
        "# makes 0 the transparent pen rather than a guess.\n"
    )

    # No writer name in this header, on purpose: both the Python derivation here and
    # the C one in engine/src/core/fmtowns.c emit these bytes, and a header that
    # named one of them would make the other's output differ for a reason that
    # means nothing. The mapping's source is the crosswalk, and that is named.
    mtsv = (
        "# MAP.TSV -- DOS art index -> tile indices into TILES, generated from\n"
        "# " + FMTOWNS_XWALK + ". Do not hand-edit.\n"
        "# Column 3 repeats the source BANK/tile tokens for provenance. A row is\n"
        "# set-valued: the engine uses the first index and keeps the rest.\n"
        "# art\ttiles\tsource\n"
    )
    for art, idxs, toks in map_lines:
        mtsv += f"{art:02X}\t{','.join(str(i) for i in idxs)}\t{','.join(toks)}\n"

    return ({"THEME.INI": ini.encode(), "TILES": tiles, "PALETTE.RGB": bytes(pal),
             "MAP.TSV": mtsv.encode()},
            ({"pool": len(order), "art": len(map_lines), "multi": multi}, problems))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--out", required=True, help="directory to write the theme into")
    ap.add_argument("--xwalk", default=None,
                    help=f"crosswalk TSV (default {FMTOWNS_XWALK})")
    args = ap.parse_args()

    files, (stats, problems) = fmtowns_theme(args.xwalk)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, body in files.items():
        (out / name).write_bytes(body)
    print(f"wrote {len(files)} file(s) into {out}: "
          f"pool={stats['pool']} art={stats['art']} multi-frame={stats['multi']}")
    for p in problems:
        print(f"  problem: {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
