#!/usr/bin/env python3
"""
fmtowns_map2h.py — compile disasm/fmtowns-crosswalk.tsv into a C header.

Why the crosswalk is embedded rather than read at run time: the derivation of a v2
FM Towns theme needs the DOS art index -> FM BANK/tile mapping, and that mapping
lives in `disasm/`, which is a repository artefact. A player who has the FM Towns
disc and a downloaded binary has neither, so a shipped `--fmtowns-media-dir` would
fail on the one machine that matters — the player's. Embedding it is the same
posture `gen_content.h` takes for the game's text: the build carries the data, and
the file is committed so a fresh clone needs nothing but the compiler.

Unlike gen_content.h, this one can always be re-derived, because its source is
committed too. So `--verify` is not a best-effort check from a missing asset; it is
an exact comparison, and it belongs in CI.

The header is a faithful copy of the crosswalk rows, in file order, with the
BANK/tile tokens exactly as written. The pool/order algorithm that turns those
tokens into TILES indices is NOT baked in — it is re-implemented in C beside them,
so the mapping data and the mapping policy stay separate and the C port can be
checked against this tool's output byte for byte.

USAGE
    python3 engine/tools/fmtowns_map2h.py -o engine/content/fmtowns_map.h
    python3 engine/tools/fmtowns_map2h.py --verify -o engine/content/fmtowns_map.h
"""

import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
XWALK = REPO / "disasm/fmtowns-crosswalk.tsv"
SCOPE = "overworld,towns"      # the crosswalk's own scope caveat, verbatim

HEADER = """/* GENERATED by engine/tools/fmtowns_map2h.py — do not edit by hand.
 *
 * The DOS art index -> FM Towns BANK/tile mapping, compiled out of
 * disasm/fmtowns-crosswalk.tsv so a shipped binary can derive a v2 FM Towns theme
 * from the player's disc without also being given the repository. Regenerate and
 * verify:
 *   python3 engine/tools/fmtowns_map2h.py --verify -o engine/content/fmtowns_map.h
 *   python3 engine/tools/fmtowns_map2h.py        -o engine/content/fmtowns_map.h
 *
 * Source: %s md5=%s
 * Rows are in crosswalk file order; tokens are exactly as written there. The
 * pool/order that numbers TILES is derived from these rows at run time, in
 * engine/src/core/fmtowns.c, so the data and the policy stay separate.
 *
 * The mapping itself is our own analysis of the two games' art, graded per row in
 * the TSV (owner = named by Paul, strong/thin/weak = derived and graded). The tile
 * ART it points at is not ours and is never committed: it is read from the player's
 * own disc at install time.
 */
#ifndef U2_CONTENT_FMTOWNS_MAP_H
#define U2_CONTENT_FMTOWNS_MAP_H

#define U2_FMTOWNS_XWALK "%s"
#define U2_FMTOWNS_SCOPE "%s"
#define U2_FMTOWNS_MAP_COUNT %d

/* art index -> comma-joined "BANK/tile" tokens, first entry is the one drawn. */
static const char *const u2_fmtowns_map[U2_FMTOWNS_MAP_COUNT] = {
%s};

#endif
"""


def load_rows(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for ln in fh:
            ln = ln.rstrip("\n")
            if not ln or ln.startswith("#"):
                continue
            cols = ln.split("\t")
            if len(cols) < 2:
                continue
            toks = [t.strip() for t in cols[1].split(",") if t.strip()]
            rows.append((int(cols[0], 16), toks))
    return rows


def render(rows):
    md5 = hashlib.md5(XWALK.read_bytes()).hexdigest()
    body = "".join('    "%s",\n' % ",".join(toks) for _, toks in rows)
    return HEADER % (XWALK.relative_to(REPO), md5,
                     XWALK.relative_to(REPO), SCOPE, len(rows), body)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--verify", action="store_true",
                    help="fail if the committed header is not what the TSV produces")
    args = ap.parse_args()

    if not XWALK.is_file():
        raise SystemExit(f"no crosswalk at {XWALK}; regenerate it with "
                         f"`python3 tools/fmtowns_xwalk.py --export`")
    rows = load_rows(XWALK)
    if len(rows) != 64:
        raise SystemExit(f"crosswalk has {len(rows)} rows, expected 64")
    missing = sorted(set(range(64)) - {a for a, _ in rows})
    if missing:
        raise SystemExit("crosswalk has no row for art "
                         + ", ".join(f"{m:02X}" for m in missing))

    text = render(rows)
    out = Path(args.out)
    if args.verify:
        if not out.is_file():
            raise SystemExit(f"{out} is missing and is committed content")
        if out.read_text() != text:
            raise SystemExit(f"{out} does not match {XWALK.relative_to(REPO)}; "
                             f"regenerate it (do not hand-edit)")
        print(f"fmtowns map ok: {len(rows)} rows, {out}")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
